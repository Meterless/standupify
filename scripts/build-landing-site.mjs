// =====================================================================
// npm run landing:site — the landing page as an uploadable folder.
//
// Writes dist-landing/ with index.html, station.js, only the media the page
// actually uses (landing/media keeps every file ever copied), an .htaccess,
// and a links.js that points the Demo and Download buttons at the web demo
// (`npm run build:web`) hosted next to it:
//
//   https://example.com/Standupify/        ← dist-landing/
//   https://example.com/Apps/Standupify/   ← dist-web/ (with downloads/)
//
//   npm run landing:site                         demo at ../Apps/Standupify/
//   npm run landing:site -- --demo <url>         anywhere else (relative or absolute)
//
// Run `npm run landing` first for the newest Station content, and
// `npm run build:web` first so the installer names and sizes are known.
// =====================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i !== -1 && args[i + 1] ? args[i + 1] : d; };
const demo = opt('demo', '../Apps/Standupify/').replace(/\/?$/, '/');
const src = path.join(root, 'landing');
const out = path.join(root, 'dist-landing');

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
const station = fs.readFileSync(path.join(src, 'station.js'), 'utf8');
fs.writeFileSync(path.join(out, 'index.html'), html);
fs.writeFileSync(path.join(out, 'station.js'), station);

// Media: the hand-picked files at the top of landing/media (the page's fallbacks)
// plus every Station file station.js names.
let bytes = 0, count = 0;
const copy = (rel) => {
  const from = path.join(src, rel), to = path.join(out, rel);
  if (!fs.existsSync(from)) return;
  fs.mkdirSync(path.dirname(to), { recursive: true });
  // A hard link costs no disk space (hundreds of MB of clips); copy where links aren't allowed.
  try { fs.linkSync(from, to); } catch { fs.copyFileSync(from, to); }
  bytes += fs.statSync(from).size; count++;
};
for (const e of fs.readdirSync(path.join(src, 'media'), { withFileTypes: true })) if (e.isFile()) copy(`media/${e.name}`);
for (const rel of new Set(station.match(/media\/station\/[a-f0-9]{40}\.[a-z0-9]+/g) || [])) copy(rel);

// Links: the demo next door, and its installers if the web build has them.
let downloads = null;
try {
  const d = JSON.parse(fs.readFileSync(path.join(root, 'dist-web', 'downloads', 'downloads.json'), 'utf8'));
  downloads = { version: d.version };
  for (const f of d.files) downloads[f.kind] = { href: demo + f.file, size: f.size };
} catch {
  console.log('No dist-web/downloads/downloads.json (npm run build:web): Download will open the demo instead.');
}
fs.writeFileSync(path.join(out, 'links.js'), `// Generated by npm run landing:site, ${new Date().toISOString()}
window.STANDUPIFY_LINKS = ${JSON.stringify({ demo, github: 'https://github.com/meterless/standupify', downloads }, null, 2)};
`);

fs.writeFileSync(path.join(out, '.htaccess'), `# Standupify landing page
DirectoryIndex index.html
Options -Indexes
AddType video/mp4 .mp4

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "\\.(jpe?g|png|gif|webp|mp4|webm)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\\.(html|js)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  Header set X-Content-Type-Options "nosniff"
</IfModule>
`);

console.log(`landing site → dist-landing/  (${count} media files, ${(bytes / 1048576).toFixed(0)} MB)`);
console.log(`Demo: ${demo}${downloads ? `  ·  installers: ${Object.keys(downloads).filter(k => k !== 'version').join(', ')} v${downloads.version}` : ''}`);
